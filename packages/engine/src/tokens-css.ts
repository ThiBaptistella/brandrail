import { flattenTokens } from "./tokens.ts";

const cssVar = (path: string) => `--${path.replace(/\./g, "-")}`;

/**
 * The Brand Kit as CSS custom properties: one variable per token (`color.action.primary` →
 * `--color-action-primary`), dark values under `[data-theme="dark"]` and `prefers-color-scheme`.
 */
export function generateTokensCss(tokens: unknown, opts: { version?: string; org?: string } = {}): string {
  const flat = flattenTokens(tokens);
  const head = `/* Generated by Brandrail from the ${opts.org ? `${opts.org} ` : ""}Brand Kit${opts.version ? ` v${opts.version}` : ""}. Do not edit: run \`npx brandrail init --from-api\` to update. */`;
  const light = flat.map((t) => `  ${cssVar(t.path)}: ${t.type === "fontFamily" ? t.value : t.value};`);
  const dark = flat.filter((t) => t.dark).map((t) => `  ${cssVar(t.path)}: ${t.dark};`);
  const out = [head, "", ":root {", ...light, "}"];
  if (dark.length) {
    out.push("", '[data-theme="dark"] {', ...dark, "}", "", "@media (prefers-color-scheme: dark) {", '  :root:not([data-theme="light"]) {', ...dark.map((l) => `  ${l}`), "  }", "}");
  }
  return `${out.join("\n")}\n`;
}
